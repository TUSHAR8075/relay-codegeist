// Renders the handover pack (Confluence storage format) and compact text for Rovo.
import { escapeXml as x, truncate } from './util.js';

const TIER_COLOUR = { critical: 'Red', high: 'Yellow', medium: 'Blue', low: 'Grey' };

function status(tier) {
  return `<ac:structured-macro ac:name="status"><ac:parameter ac:name="colour">${TIER_COLOUR[tier] || 'Grey'}</ac:parameter><ac:parameter ac:name="title">${x(tier.toUpperCase())}</ac:parameter></ac:structured-macro>`;
}

function link(url, text) {
  return url ? `<a href="${x(url)}">${x(text)}</a>` : x(text);
}

function nextStep(item) {
  if (item.nextStep) return item.nextStep;
  if (item.type === 'pr') return 'Get the review finished and merge, or hand the branch over.';
  if (item.type === 'page') return 'Keep the page up to date; the new owner answers questions on it.';
  if (item.statusCategory === 'indeterminate') return 'Continue the work in progress; check the latest comment first.';
  return 'Pick up when it becomes the top priority.';
}

export function packTitle(record) {
  return `Handover: ${record.person.name} (${record.window.start} to ${record.window.end})`;
}

export function renderPack(record) {
  const { person, window, items, summary } = record;
  const rows = items
    .map((it) => {
      const owner = it.chosenOwner ? x(it.chosenOwner.name) : '<em>Unassigned, needs a decision</em>';
      const ask = (it.otherContributors || []).slice(0, 2).map((p) => x(p.name)).join(', ') || x(person.name);
      return `<tr>
<td>${link(it.url, `${it.key ? `${it.key} ` : ''}${it.title}`)}</td>
<td>${status(it.risk.tier)} ${it.risk.score}</td>
<td>${x(it.status || '')}</td>
<td>${x(nextStep(it))}</td>
<td>${owner}</td>
<td>${ask}</td>
</tr>`;
    })
    .join('\n');

  const context = items
    .filter((it) => it.lastNote || it.risk.reasons.length)
    .map(
      (it) => `<h3>${link(it.url, `${it.key ? `${it.key} ` : ''}${it.title}`)}</h3>
<p><strong>Why it matters:</strong> ${x(it.risk.reasons.join('; ') || 'routine')}</p>
${it.lastNote ? `<p><strong>Latest note from ${x(person.name)}:</strong> ${x(truncate(it.lastNote, 400))}</p>` : ''}
${it.suggestions?.length ? `<p><strong>Other possible owners:</strong> ${it.suggestions.slice(1).map((s) => x(`${s.name} (${s.why.join(', ')})`)).join('; ') || 'none'}</p>` : ''}`,
    )
    .join('\n');

  return `<ac:structured-macro ac:name="info"><ac:rich-text-body>
<p>${x(person.name)} is away from <strong>${x(window.start)}</strong> to <strong>${x(window.end)}</strong>. Relay found <strong>${summary.total}</strong> open items: ${summary.critical} critical, ${summary.high} high, ${summary.medium} medium, ${summary.low} low.</p>
<p>Every row links to its source. Generated by Relay from the Teamwork Graph, Jira and Confluence.</p>
</ac:rich-text-body></ac:structured-macro>
<h2>Work being handed over</h2>
<table><tbody>
<tr><th>Item</th><th>Risk</th><th>Status</th><th>Next step</th><th>New owner</th><th>Ask about it</th></tr>
${rows}
</tbody></table>
<h2>Context, item by item</h2>
${context || '<p>No extra context recorded.</p>'}
<h2>When ${x(person.name)} is back</h2>
<ac:task-list>
<ac:task><ac:task-status>incomplete</ac:task-status><ac:task-body>Ask Relay: "I'm back. What changed while I was away?"</ac:task-body></ac:task>
<ac:task><ac:task-status>incomplete</ac:task-status><ac:task-body>Decide which items move back and which stay with the new owner.</ac:task-body></ac:task>
</ac:task-list>`;
}

/** Compact JSON for Rovo (keeps responses far below the ~1 MB practical limit). */
export function compactItems(items, limit = 40) {
  return items.slice(0, limit).map((it) => ({
    key: it.key || null,
    type: it.type,
    title: truncate(it.title, 120),
    url: it.url,
    status: it.status,
    dueDate: it.dueDate || null,
    risk: it.risk?.score,
    tier: it.risk?.tier,
    reasons: it.risk?.reasons,
    suggestedOwner: it.chosenOwner?.name || null,
    alternatives: (it.suggestions || []).slice(1).map((s) => s.name),
    whyOwner: it.suggestions?.[0]?.why || [],
  }));
}
